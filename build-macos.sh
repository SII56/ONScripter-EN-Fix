#!/bin/bash
# build-macos.sh - build ONScripter-EN on macOS
# usage: ./build-macos.sh [extra make arguments]
set -euo pipefail

cd "$(dirname "$0")"
ROOT="$PWD"
EXT="$ROOT/extlib"

# Use a clean PATH. Some environments (IDEs, bundlers) prepend shim
# directories with spaces in their path, which breaks autoconf's
# detection of sed / ld.
export PATH="/opt/homebrew/bin:/opt/homebrew/sbin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
export PATH="/opt/homebrew/opt/libtool/libexec/gnubin:$PATH"

need=(sdl12-compat smpeg libogg libvorbis mad bzip2 jpeg dylibbundler autoconf automake libtool)
missing=()
for f in "${need[@]}"; do
    brew list --formula "$f" >/dev/null 2>&1 || missing+=("$f")
done
if [ ${#missing[@]} -gt 0 ]; then
    echo "==> installing dependencies: ${missing[*]}"
    brew install "${missing[@]}"
fi

# The bundled aclocal.m4 was generated by an older automake, and a
# mismatch produces "aclocal-1.16: command not found", so regenerate it.
# Note: in a fresh clone configure and configure.ac share the same mtime,
# so an -nt test is false and would skip this step; always run it instead
# (it only takes a few seconds).
for d in libogg-1.3.5 libvorbis-1.3.7; do
    echo "==> autoreconf $d"
    ( cd "$EXT/src/$d" && autoreconf -fi >/dev/null )
done

# The macOS-specific configure flags for SDL_ttf / SDL_image live in
# Makefile.extlibs (see the ifeq ($(SYS),MacOSX) block there). Nothing is
# pre-built by hand here; make's dependency order handles it.

if [ ! -f Makefile ]; then
    echo "==> configure"
    ./configure
fi

echo "==> make"
make "$@"

echo
echo "done: $ROOT/onscripter-en"
file "$ROOT/onscripter-en"
